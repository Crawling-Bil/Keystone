"""Write the tree as an "LLD Content Index" workbook.

The format is the one the Document Generator's importer.py reads:

* sheet "Index", header row "No | Judul Heading | Level | Tipe Konten |
  Isi / Nama Sheet Rujukan | Catatan"; Level is "H1".."H9";
* Paragraf: text in Isi, or the name of a sheet whose column 2 holds one
  paragraph per row (used for more than one paragraph);
* Tabel: Isi is the name of a sheet with a header row and data rows (a
  table without rows is dropped by the importer, so empty tables carry a
  "TBD" row); Catatan becomes the table caption;
* Gambar: an empty image block, caption from Catatan;
* cell colours (rack status) are solid fills on the data cells; the
  Document Generator copies them to the Word table;
* a row with an empty Judul Heading adds one more block to the heading
  above it (paragraph + table + image under one heading). The Document
  Generator reads these with the multi-block importer (feat/multi-block-import); an older
  importer skips them and keeps the first block only.

Sheet names are unique, at most 31 characters, and free of []:*?/\\ .
"""

from __future__ import annotations

import io
import re

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

INDEX_HEADERS = ["No", "Judul Heading", "Level", "Tipe Konten", "Isi / Nama Sheet Rujukan", "Catatan"]
_BAD_SHEET_CHARS = re.compile(r"[\[\]:*?/\\]")
_HEADER_FILL = PatternFill("solid", fgColor="0F8A7E")
_TBD_FILL = PatternFill("solid", fgColor="FFF2CC")
_MAX_CELL = 32000  # Excel's limit is 32767 characters per cell


def _sheet_name(hint: str, used: set) -> str:
    base = _BAD_SHEET_CHARS.sub("-", hint).strip().strip("'") or "Sheet"
    base = re.sub(r"\s+", " ", base)[:31]
    if base.lower() == "index":
        base = "Index data"
    name, n = base, 2
    while name.lower() in used:
        suffix = f" {n}"
        name = base[: 31 - len(suffix)] + suffix
        n += 1
    used.add(name.lower())
    return name


def _numbers(nodes: list) -> list[str]:
    counters = [0] * 10
    out = []
    for node in nodes:
        level = max(1, min(node.level, 9))
        counters[level - 1] += 1
        for i in range(level, 10):
            counters[i] = 0
        out.append(".".join(str(c) for c in counters[:level]))
    return out


def _cell(value) -> str:
    text = "" if value is None else str(value)
    return text if len(text) <= _MAX_CELL else text[: _MAX_CELL - 20] + "\n... (truncated)"


def write(nodes: list, project: dict) -> bytes:
    workbook = Workbook()
    index = workbook.active
    index.title = "Index"
    title = f"LLD Content Index - {project.get('project_name') or 'Project'}"
    index.append([title])
    index["A1"].font = Font(bold=True, size=13)
    index.append([f"Customer: {project.get('customer') or '-'}    Generated by Keystone LLD Index. "
                  "Yellow rows still need manual content (TBD, images)."])
    index.append([])
    index.append(INDEX_HEADERS)
    for cell in index[4]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = _HEADER_FILL
    used = {"index"}
    def content(node):
        kind, isi, note = "", "", ""
        if node.kind == "paragraph":
            kind = "Paragraf"
            if len(node.paragraphs) == 1:
                isi = node.paragraphs[0]
            else:
                isi = _sheet_name(node.sheet_hint or node.title, used)
                sheet = workbook.create_sheet(isi)
                sheet.append(["No", "Isi"])
                for i, text in enumerate(node.paragraphs, start=1):
                    sheet.append([i, _cell(text)])
                sheet.column_dimensions["B"].width = 110
        elif node.kind == "table":
            kind = "Tabel"
            note = node.caption or node.title
            isi = _sheet_name(node.sheet_hint or node.title, used)
            sheet = workbook.create_sheet(isi)
            sheet.append([_cell(h) for h in node.headers])
            for cell in sheet[1]:
                cell.font = Font(bold=True)
            for row in node.rows:
                sheet.append([_cell(v) for v in row])
            for r, c, n_rows, n_cols in node.merges:
                sheet.merge_cells(start_row=2 + r, start_column=1 + c, end_row=1 + r + n_rows, end_column=c + n_cols)
            for r, c, color in node.fills:
                sheet.cell(row=2 + r, column=1 + c).fill = PatternFill("solid", fgColor=color)
            for col, header in enumerate(node.headers, start=1):
                longest = max([len(str(header))] + [min(len(str(r[col - 1])) if col - 1 < len(r) else 0, 60) for r in node.rows[:200]])
                sheet.column_dimensions[get_column_letter(col)].width = max(8, min(longest + 2, 70))
            for row in sheet.iter_rows(min_row=2):
                for cell in row:
                    cell.alignment = Alignment(wrap_text=True, vertical="top")
        elif node.kind == "image":
            kind = "Gambar"
            note = node.caption or node.title
        return kind, isi, note

    for number, node in zip(_numbers(nodes), nodes):
        kind, isi, note = content(node)
        index.append([number, node.title, f"H{max(1, min(node.level, 9))}", kind, _cell(isi), note])
        if node.placeholder or node.kind == "image":
            for cell in index[index.max_row]:
                cell.fill = _TBD_FILL
        # extra blocks under the same heading: No / Judul / Level stay empty
        for extra in node.more:
            kind, isi, note = content(extra)
            index.append(["", "", "", kind, _cell(isi), note])
            if extra.placeholder or extra.kind == "image":
                for cell in index[index.max_row]:
                    cell.fill = _TBD_FILL
    for col, width in zip("ABCDEF", (10, 52, 7, 12, 60, 40)):
        index.column_dimensions[col].width = width
    index.freeze_panes = "A5"
    out = io.BytesIO()
    workbook.save(out)
    return out.getvalue()
